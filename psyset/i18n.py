def t(lang: str, key: str, **fmt) -> str:
    """Translate `key`; unknown language -> English, unknown key -> the key itself. Never raises."""
    s = STRINGS.get(lang, STRINGS["en"]).get(key, key)
    if not fmt:
        return s
    try:
        return s.format(**fmt)
    except (KeyError, IndexError, ValueError):
        return s
